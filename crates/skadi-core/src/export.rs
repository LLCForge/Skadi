//! Profildeki uygulamaları başka araçların biçimlerine dönüştürür: Ansible, Homebrew Brewfile ve
//! `winget import` dosyası. Yalnızca katalogdaki doğrulanmış paket kimlikleri kullanılır; her
//! değer JSON dizesi olarak yazılır (JSON dizesi geçerli YAML ve Ruby dizesidir).

use crate::{catalog::App, manager::ManagerId};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExportFormat {
    Ansible,
    Brewfile,
    Winget,
    /// home-manager `home.packages` parçası.
    Nix,
    /// Intune platform betiği ya da Win32 uygulama kurulum komutu (SYSTEM olarak çalışır).
    Intune,
}

impl ExportFormat {
    pub fn parse(text: &str) -> Option<Self> {
        match text {
            "ansible" => Some(Self::Ansible),
            "brewfile" => Some(Self::Brewfile),
            "winget" => Some(Self::Winget),
            "nix" => Some(Self::Nix),
            "intune" => Some(Self::Intune),
            _ => None,
        }
    }
}

fn quote(text: &str) -> String {
    serde_json::Value::from(text).to_string()
}

fn ids(apps: &[&App], id: ManagerId) -> Vec<String> {
    apps.iter()
        .filter_map(|app| app.packages.get(&id))
        .map(|p| quote(p))
        .collect()
}

/// Ansible'ın `pkg_mgr` değerleri ile Skadi yöneticileri.
const LINUX: [(ManagerId, &str); 6] = [
    (ManagerId::Apt, "apt"),
    (ManagerId::Dnf, "dnf"),
    (ManagerId::Yum, "yum"),
    (ManagerId::Zypper, "zypper"),
    (ManagerId::Pacman, "pacman"),
    (ManagerId::Apk, "apk"),
];

fn task(out: &mut String, name: &str, module: &str, packages: &[String], extra: &str, when: &str) {
    if packages.is_empty() {
        return;
    }
    out.push_str(&format!(
        "    - name: {name}\n      {module}:\n        name: [{}]\n        state: present\n{extra}      when: {when}\n",
        packages.join(", ")
    ));
}

pub fn render(format: ExportFormat, apps: &[&App]) -> String {
    match format {
        ExportFormat::Brewfile => {
            let mut out = String::from("# Generated by Skadi. Install with: brew bundle\n");
            for app in apps {
                if let Some(id) = app.packages.get(&ManagerId::Brew) {
                    out.push_str(&format!("brew {}\n", quote(id)));
                } else if let Some(id) = app.packages.get(&ManagerId::BrewCask) {
                    out.push_str(&format!("cask {}\n", quote(id)));
                }
            }
            out
        }
        ExportFormat::Nix => {
            let mut out = String::from(
                "# Generated by Skadi. Add to your home-manager configuration.\n{ pkgs, ... }: {\n  home.packages = with pkgs; [\n",
            );
            for app in apps {
                // Katalogdaki Nix kimlikleri `nixpkgs#ad` biçimindedir.
                if let Some(name) = app
                    .packages
                    .get(&ManagerId::Nix)
                    .and_then(|p| p.strip_prefix("nixpkgs#"))
                {
                    out.push_str(&format!("    {name}\n"));
                }
            }
            out.push_str("  ];\n}\n");
            out
        }
        ExportFormat::Intune => {
            let ids: Vec<String> = apps
                .iter()
                .filter_map(|a| a.packages.get(&ManagerId::Winget))
                .map(|id| format!("'{id}'"))
                .collect();
            format!(
                "# Generated by Skadi. Use as an Intune platform script, or as the install command of a\n\
                 # Win32 app: powershell.exe -ExecutionPolicy Bypass -File skadi-intune.ps1\n\
                 $ErrorActionPreference = 'Stop'\n\
                 # Intune runs scripts as SYSTEM, where winget is not on PATH.\n\
                 $winget = Get-ChildItem \"$env:ProgramFiles\\WindowsApps\\Microsoft.DesktopAppInstaller_*__8wekyb3d8bbwe\\winget.exe\" |\n\
                 \x20   Sort-Object LastWriteTime -Descending | Select-Object -First 1 -ExpandProperty FullName\n\
                 if (-not $winget) {{ throw 'winget was not found' }}\n\
                 $apps = @({})\n\
                 foreach ($id in $apps) {{\n\
                 \x20   & $winget install --id $id --exact --silent --scope machine --accept-package-agreements --accept-source-agreements --disable-interactivity\n\
                 }}\n",
                ids.join(", ")
            )
        }
        ExportFormat::Winget => {
            let source = |name: &str, argument: &str, identifier: &str, kind: &str, id: ManagerId| {
                let packages: Vec<_> = apps
                    .iter()
                    .filter_map(|a| a.packages.get(&id))
                    .map(|p| serde_json::json!({ "PackageIdentifier": p }))
                    .collect();
                (!packages.is_empty()).then(|| {
                    serde_json::json!({
                        "Packages": packages,
                        "SourceDetails": { "Argument": argument, "Identifier": identifier, "Name": name, "Type": kind },
                    })
                })
            };
            let sources: Vec<_> = [
                source(
                    "winget",
                    "https://cdn.winget.microsoft.com/cache",
                    "Microsoft.Winget.Source_8wekyb3d8bbwe",
                    "Microsoft.PreIndexed.Package",
                    ManagerId::Winget,
                ),
                source(
                    "msstore",
                    "https://storeedgefd.dsx.mp.microsoft.com/v9.0",
                    "StoreEdgeFD",
                    "Microsoft.Rest",
                    ManagerId::Msstore,
                ),
            ]
            .into_iter()
            .flatten()
            .collect();
            let document = serde_json::json!({
                "$schema": "https://aka.ms/winget-packages.schema.2.0.json",
                "CreationDate": "1970-01-01T00:00:00.000-00:00",
                "Sources": sources,
                "WinGetVersion": "1.0",
            });
            serde_json::to_string_pretty(&document).unwrap_or_default() + "\n"
        }
        ExportFormat::Ansible => {
            let mut out = String::from(
                "# Generated by Skadi. Review before running: ansible-playbook -i <inventory> <this file>\n\
                 # Needs the community.general and chocolatey.chocolatey collections.\n\
                 - name: Skadi apps\n  hosts: all\n  tasks:\n",
            );
            for (id, pkg_mgr) in LINUX {
                task(
                    &mut out,
                    &format!("System packages ({pkg_mgr})"),
                    "ansible.builtin.package",
                    &ids(apps, id),
                    "      become: true\n",
                    &format!("ansible_facts.pkg_mgr == \"{pkg_mgr}\""),
                );
            }
            // Dağıtım paketi olmayan uygulamalar Flatpak'ten, o da yoksa Snap'ten gelir (Skadi'nin seçimi gibi).
            let without_system: Vec<&App> = apps
                .iter()
                .copied()
                .filter(|a| !LINUX.iter().any(|(id, _)| a.packages.contains_key(id)))
                .collect();
            let flatpak_only: Vec<&App> = without_system
                .iter()
                .copied()
                .filter(|a| a.packages.contains_key(&ManagerId::Flatpak))
                .collect();
            let snap_only: Vec<&App> = without_system
                .iter()
                .copied()
                .filter(|a| !a.packages.contains_key(&ManagerId::Flatpak))
                .collect();
            let linux = "ansible_facts.system == \"Linux\"";
            task(
                &mut out,
                "Flatpak apps",
                "community.general.flatpak",
                &ids(&flatpak_only, ManagerId::Flatpak),
                "      become: true\n",
                linux,
            );
            task(
                &mut out,
                "Snap apps",
                "community.general.snap",
                &ids(&snap_only, ManagerId::Snap),
                "      become: true\n",
                linux,
            );
            let mac = "ansible_facts.os_family == \"Darwin\"";
            task(
                &mut out,
                "Homebrew formulae",
                "community.general.homebrew",
                &ids(apps, ManagerId::Brew),
                "",
                mac,
            );
            task(
                &mut out,
                "Homebrew casks",
                "community.general.homebrew_cask",
                &ids(apps, ManagerId::BrewCask),
                "",
                mac,
            );
            task(
                &mut out,
                "Chocolatey packages",
                "chocolatey.chocolatey.win_chocolatey",
                &ids(apps, ManagerId::Choco),
                "",
                "ansible_facts.os_family == \"Windows\"",
            );
            out
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::Catalog;

    #[test]
    fn renders_every_format_from_catalog_ids() {
        let catalog = Catalog::builtin().unwrap();
        let apps: Vec<&App> = ["git", "firefox", "vlc"]
            .iter()
            .filter_map(|id| catalog.get(id))
            .collect();
        assert_eq!(apps.len(), 3);

        let brew = render(ExportFormat::Brewfile, &apps);
        assert!(brew.contains("brew \"git\"") && brew.contains("cask \"firefox\""));

        let winget: serde_json::Value = serde_json::from_str(&render(ExportFormat::Winget, &apps)).unwrap();
        let packages = &winget["Sources"][0]["Packages"];
        assert!(
            packages
                .as_array()
                .unwrap()
                .iter()
                .any(|p| p["PackageIdentifier"] == "Git.Git")
        );

        let ansible = render(ExportFormat::Ansible, &apps);
        assert!(ansible.contains("when: ansible_facts.pkg_mgr == \"apt\""));
        assert!(ansible.contains("\"git\""));
        assert!(ExportFormat::parse("shell").is_none());
        let nix = render(ExportFormat::Nix, &apps);
        assert!(nix.contains("    git\n") && nix.contains("home.packages"));
        let intune = render(ExportFormat::Intune, &apps);
        assert!(intune.contains("'Git.Git'") && intune.contains("--scope machine"));
    }
}
